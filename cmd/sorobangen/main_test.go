func TestRun_FromWasm_WritesPlaceholder(t *testing.T) {
	wasm := buildWasm(t, "contractspecv0", encodeEntries(t, []xdr.ScSpecEntry{fnEntry(t, "transfer")}))
	dir := t.TempDir()
	wasmPath := filepath.Join(dir, "c.wasm")
	if err := os.WriteFile(wasmPath, wasm, 0o644); err != nil {
		t.Fatalf("seed wasm: %v", err)
	}
	outDir := filepath.Join(dir, "out")

	if err := run([]string{"-wasm", wasmPath, "-out", outDir, "-package", "token"}, io.Discard); err != nil {
		t.Fatalf("run: %v", err)
	}

	got, err := os.ReadFile(outputFilePath(outDir, "token"))
	if err != nil {
		t.Fatalf("read output: %v", err)
	}
	body := string(got)
	if !strings.Contains(body, "Code generated by sorobangen") {
		t.Errorf("missing generated header in %q", body)
	}
	if !strings.Contains(body, "package token") {
		t.Errorf("missing package decl in %q", body)
	}
	if !strings.Contains(body, "SpecEntryCount = 1") {
		t.Errorf("expected entry count 1, got %q", body)
	}
}

