func TestRun_FlagValidation(t *testing.T) {
	dir := t.TempDir()
	cases := []struct {
		name    string
		args    []string
		wantSub string
	}{
		{
			name:    "no input",
			args:    []string{"-out", dir, "-package", "p"},
			wantSub: "-wasm or -spec",
		},
		{
			name:    "both inputs",
			args:    []string{"-wasm", "a", "-spec", "b", "-out", dir, "-package", "p"},
			wantSub: "mutually exclusive",
		},
		{
			name:    "missing out",
			args:    []string{"-wasm", "a", "-package", "p"},
			wantSub: "-out",
		},
		{
			name:    "missing package",
			args:    []string{"-wasm", "a", "-out", dir},
			wantSub: "-package",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			err := run(tc.args, io.Discard)
			if err == nil {
				t.Fatal("expected error")
			}
			if !strings.Contains(err.Error(), tc.wantSub) {
				t.Errorf("error %q missing %q", err, tc.wantSub)
			}
		})
	}
}

// --- helpers (local to this test file so the CLI has no test-only exports) ---

func fnEntry(t *testing.T, name string) xdr.ScSpecEntry {
	t.Helper()
	fn := xdr.ScSpecFunctionV0{
		Name:    xdr.ScSymbol(name),
		Inputs:  nil,
		Outputs: nil,
	}
	e, err := xdr.NewScSpecEntry(xdr.ScSpecEntryKindScSpecEntryFunctionV0, fn)
	if err != nil {
		t.Fatalf("build entry: %v", err)
	}
	return e
}

func encodeEntries(t *testing.T, entries []xdr.ScSpecEntry) []byte {
	t.Helper()
	var buf bytes.Buffer
	for i := range entries {
		if _, err := xdr.Marshal(&buf, &entries[i]); err != nil {
			t.Fatalf("marshal entry: %v", err)
		}
	}
	return buf.Bytes()
}

// buildWasm produces the minimum well-formed WebAssembly module that
// contains a single custom section. Mirrors the helper used by the
// contract package's spec_test.go.
func buildWasm(t *testing.T, name string, payload []byte) []byte {
	t.Helper()
	var w bytes.Buffer
	w.Write([]byte{0x00, 'a', 's', 'm', 0x01, 0x00, 0x00, 0x00})

	var body bytes.Buffer
	writeVarUint32(&body, uint32(len(name)))
	body.WriteString(name)
	body.Write(payload)

	w.WriteByte(0x00) // custom section id
	writeVarUint32(&w, uint32(body.Len()))
	w.Write(body.Bytes())
	return w.Bytes()
}

func writeVarUint32(w *bytes.Buffer, v uint32) {
	for {
		b := byte(v & 0x7f)
		v >>= 7
		if v != 0 {
			b |= 0x80
		}
		w.WriteByte(b)
		if v == 0 {
			return
		}
	}
}
